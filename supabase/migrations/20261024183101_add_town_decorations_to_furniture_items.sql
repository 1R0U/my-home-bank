-- アプリの一覧とずれたら tests/townDecorations.test.mjs が落ちる。
-- 見た目のアセットは、すべて販売するアセット（store_assets）にすでにある（外部キーで確かめる）。
--
-- 【位置の範囲】
-- house_furniture_layouts の位置は ±100 に制限している。町の飾りは散らす範囲（±34）の中にあり、
